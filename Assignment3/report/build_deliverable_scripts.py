#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
build_deliverable_scripts.py
============================
Regenerate the two single-file deliverables from the source files in sql/ and cypher/:
  sql/warehouse_script.sql          (DDL + loads + Q1-Q5 + optimization + R1-R3)
  cypher/neo4j_script.cypher        (constraints + load statements + N1-N6)
由 sql/ 与 cypher/ 下的源文件重新生成两个单文件交付脚本。源文件改过之后重新运行本脚本即可。
Usage / 用法:  python report/build_deliverable_scripts.py
"""

import importlib.util
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)


def rd(p):
    return open(p, encoding="utf-8").read().rstrip() + "\n"


def banner(t):
    return "\n-- " + "=" * 86 + "\n-- " + t + "\n-- " + "=" * 86 + "\n\n"


# ---------------------------------------------------------------- warehouse script / 仓库脚本
spec = importlib.util.spec_from_file_location("ld", os.path.join("pipeline", "05_load_snowflake.py"))
ld = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ld)

out = ["""-- ======================================================================================
-- warehouse_script.sql  -  Assignment 3, warehouse (Snowflake) deliverable
-- 作业 3 数据仓库交付脚本(Snowflake)
-- One file with: (1) DDL (tables + three Gold views), (2) load statements, (3) five analytical queries, (4) the Q5 optimization
-- (rewrite A, pre-computed table B, clustering C), (5) the three Part 4a queries.
-- 一个文件包含:DDL(表 + 3 个 Gold 视图)、加载语句、5 条分析查询、Q5 优化(A 改写 / B 预计算表 / C 聚类)、第 4a 部分的 3 条查询。
-- The files in sql/ are the source; this file is their concatenation (generated by report/build_deliverable_scripts.py, do not edit by hand).
-- sql/ 目录下的文件是源文件,本文件是它们的拼接(自动生成,请勿手改)。
-- Credentials are never stored here: the Python loaders read SNOWFLAKE_ACCOUNT / SNOWFLAKE_USER / SNOWFLAKE_PASSWORD.
-- 这里不含任何凭据:Python 加载脚本从环境变量读取。
-- ======================================================================================
"""]
out.append(banner("1. DDL: warehouse, database, schemas, tables, Gold views / 建库建表与 Gold 视图") + rd("sql/01_ddl_and_views.sql"))

load = ["-- PUT is a client command (SnowSQL / Python connector), it cannot run in a Snowsight worksheet; pipeline/05_load_snowflake.py does PUT + COPY INTO for every table.",
        "-- PUT 是客户端命令,不能在 Snowsight 工作表里运行;pipeline/05_load_snowflake.py 对每张表执行 PUT + COPY INTO。",
        "-- The COPY INTO statements below are the ones the loader runs (one stage sub-folder per table).",
        "-- 下面的 COPY INTO 就是加载脚本实际执行的语句(每张表一个 stage 子目录)。", ""]
for table, rel in ld.CSV_TABLES:
    sub = table.replace(".", "_").lower()
    load.append(f"-- PUT 'file://<local path>/{rel}' @PODCAST_DW.STAGE.LOAD_STAGE/{sub}/ AUTO_COMPRESS=TRUE OVERWRITE=TRUE;")
    load.append(f"COPY INTO PODCAST_DW.{table} FROM @PODCAST_DW.STAGE.LOAD_STAGE/{sub}/ "
                "FILE_FORMAT=(TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='\"' NULL_IF=('') EMPTY_FIELD_AS_NULL=TRUE) ON_ERROR=ABORT_STATEMENT;")
    load.append("")
load.append("-- Bronze: raw API responses, one JSON object per line (VARIANT columns) / Bronze:原始 API 响应,每行一个 JSON")
load.append("COPY INTO PODCAST_DW.BRONZE.API_RAW FROM (SELECT $1:source_name::VARCHAR, $1:ingested_at::TIMESTAMP_TZ, $1:request_url::VARCHAR, "
            "$1:request_params, $1:http_status::NUMBER, $1:raw_payload FROM @PODCAST_DW.STAGE.LOAD_STAGE/bronze_api_raw/) "
            "FILE_FORMAT=(TYPE=JSON) ON_ERROR=ABORT_STATEMENT;")
out.append(banner("2. Load statements / 加载语句") + "\n".join(load) + "\n")
out.append(banner("3. Analytical queries Q1-Q5 (ROLLUP, GROUPING SETS, SCD2, window, retention) / 5 条分析查询") + rd("sql/02_analytical_queries.sql"))
out.append(banner("4. Optimization of Q5 / Q5 优化") +
           "-- 4a. Version A (rewrite) and version B (reads the pre-computed table) / 版本 A(改写)与 B(读预计算表)\n" + rd("sql/03_q5_optimizations.sql") +
           "\n-- 4b. Build the pre-computed table for B (run once, 1.3 s) / 构建 B 用的预计算表(只需运行一次)\n" + rd("sql/03a_setup_agg_table.sql") +
           "\n-- 4c. Clustering test: on, then off again (no effect was measured) / 聚类测试:开启后又关闭(未测得效果)\n" + rd("sql/03c_cluster_on.sql") + "\n" + rd("sql/03c_cluster_off.sql"))
out.append(banner("5. Part 4a: three warehouse queries (time series, CUBE, SCD2 + running total) / 第 4a 部分的 3 条查询") + rd("sql/04_part4a_queries.sql"))
out.append(banner("6. SCD2 proof: expired and active versions of two creators / SCD2 证明:两位创作者的过期版本与当前版本") +
           "SELECT creator_sk, creator_id, plan_tier, valid_from, valid_to, is_current\nFROM STAR.DIM_CREATOR\nWHERE creator_id IN (5, 26)\nORDER BY creator_id, valid_from;\n")
open("sql/warehouse_script.sql", "w", encoding="utf-8").write("".join(out))
print("sql/warehouse_script.sql:", len("".join(out).splitlines()), "lines")

# ---------------------------------------------------------------- neo4j script / 图脚本
q = rd("cypher/01_queries.cypher")
q = q[q.index("// @N1"):]
head = '''// ======================================================================================
// neo4j_script.cypher  -  Assignment 3, Neo4j Aura deliverable
// 作业 3 Neo4j Aura 交付脚本
// Contents / 内容: (1) constraints, (2) the load statements, (3) all six Cypher queries (N1-N3 Part 3, N4-N6 Part 4b).
// (1) 唯一约束 (2) 加载语句 (3) 全部 6 条 Cypher 查询。
// The full load (about 9,400 nodes and 43,700 relationships) is run by pipeline/07_load_neo4j.py, which passes the rows
// as the parameter $rows in batches of 1000 (UNWIND $rows AS r ...). The statements below mirror those in the script, so they can
// be pasted into Neo4j Browser after  :param rows => [ {...}, ... ]  for a small test.
// 完整加载由 pipeline/07_load_neo4j.py 执行,按每批 1000 行以参数 $rows 传入;下面的语句与脚本一致。
// A hop is one relationship (edge) of a path. / 一跳 = 路径上的一条关系。
// No credentials are stored here (NEO4J_URI / NEO4J_USER / NEO4J_PASSWORD come from the environment).
// 这里不含凭据。This file is generated by report/build_deliverable_scripts.py.
// ======================================================================================

// ---------- 1. Constraints (one uniqueness constraint per node label) / 唯一约束 ----------
CREATE CONSTRAINT listener_key IF NOT EXISTS FOR (n:Listener) REQUIRE n.listener_key IS UNIQUE;
CREATE CONSTRAINT show_id      IF NOT EXISTS FOR (n:Show)     REQUIRE n.show_id IS UNIQUE;
CREATE CONSTRAINT creator_id   IF NOT EXISTS FOR (n:Creator)  REQUIRE n.creator_id IS UNIQUE;
CREATE CONSTRAINT category_id  IF NOT EXISTS FOR (n:Category) REQUIRE n.category_id IS UNIQUE;
CREATE CONSTRAINT episode_id   IF NOT EXISTS FOR (n:Episode)  REQUIRE n.episode_id IS UNIQUE;
CREATE CONSTRAINT guest_id     IF NOT EXISTS FOR (n:Guest)    REQUIRE n.guest_id IS UNIQUE;

// ---------- 2. Load statements (each is run with UNWIND $rows AS r in front) / 加载语句 ----------
// Nodes / 节点
UNWIND $rows AS r MERGE (n:Listener {listener_key: r.listener_key}) SET n.country_code = r.country_code;
UNWIND $rows AS r MERGE (n:Creator {creator_id: r.creator_id}) SET n.plan_tier = r.plan_tier;
UNWIND $rows AS r MERGE (n:Category {category_id: r.category_id}) SET n.name = r.category_name;
UNWIND $rows AS r MERGE (n:Guest {guest_id: r.guest_id});
// Relationships and the nodes that carry them / 关系
UNWIND $rows AS r MATCH (c:Category {category_id: r.category_id}), (p:Category {category_id: r.parent_category_id}) MERGE (c)-[:SUBCATEGORY_OF]->(p);
UNWIND $rows AS r MERGE (n:Show {show_id: r.show_id}) SET n.title = r.show_title
  WITH n, r MATCH (c:Creator {creator_id: r.creator_id}) MERGE (c)-[:PUBLISHES]->(n)
  WITH n, r MATCH (k:Category {category_id: r.category_id}) MERGE (n)-[:IN_CATEGORY]->(k);
UNWIND $rows AS r MERGE (n:Episode {episode_id: r.episode_id}) SET n.title = r.episode_title, n.duration_sec = r.episode_duration_sec, n.published = r.episode_publish_date
  WITH n, r MATCH (sh:Show {show_id: r.show_id}) MERGE (n)-[:OF_SHOW]->(sh);
UNWIND $rows AS r MATCH (g:Guest {guest_id: r.guest_id}), (e:Episode {episode_id: r.episode_id}) MERGE (g)-[:APPEARED_ON]->(e);
UNWIND $rows AS r MATCH (l:Listener {listener_key: r.listener_key}), (sh:Show {show_id: r.show_id}) MERGE (l)-[x:SUBSCRIBED_TO]->(sh) SET x.on = r.subscribed_on;
UNWIND $rows AS r MATCH (l:Listener {listener_key: r.listener_key}), (sh:Show {show_id: r.show_id}) MERGE (l)-[x:LISTENED_TO]->(sh) SET x.sessions = r.sessions, x.seconds = r.seconds, x.completed = r.completed;

// ---------- 3. Queries / 查询 ----------

'''
open("cypher/neo4j_script.cypher", "w", encoding="utf-8").write(head + q)
print("cypher/neo4j_script.cypher: done")
